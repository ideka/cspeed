"""Generate the N64Recomp symbol file (TOML) from the ROM + Binary Ninja seeds + our names.

  python tools/gen_syms.py            -> writes cspeed.us.syms.toml in the repo root

Sections: one per code segment ('boot', 'main'), sized to the detected end of code.
Functions: extents from funcbounds.compute(); names from symbols/functions.json,
otherwise func_XXXXXXXX. symbols/recomp_names.json renames some of them for the recompiler only.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, HERE)
from n64feat import load_all      # noqa: E402
import funcbounds                 # noqa: E402

NAMES = os.path.join(ROOT, "symbols", "functions.json")
RECOMP_NAMES = os.path.join(ROOT, "symbols", "recomp_names.json")
OUT = os.path.join(ROOT, "cspeed.us.syms.toml")


def main():
    rom, segs, A = load_all()
    funcs = funcbounds.compute(A)
    names = {int(k, 16): v for k, v in json.load(open(NAMES, encoding="utf-8")).items() if not k.startswith("_")}
    recomp_names = {k: v for k, v in json.load(open(RECOMP_NAMES, encoding="utf-8")).items() if k != "_comment"}
    missing = set(recomp_names) - set(names.values())
    if missing:
        sys.exit("recomp_names.json renames unknown functions: %s" % ", ".join(sorted(missing)))
    # Binary Ninja sometimes starts a function on the nop padding before it; our walker
    # starts at the first real instruction. Move such names forward over the padding.
    starts = {f[0] for f in funcs}
    for a in sorted(names):
        if a not in starts:
            b = a
            while A.word(b) == 0 and b < a + 64:
                b += 4
            if b != a and b in starts:
                names[b] = names.pop(a)
                print("note: %s moved from %08X to %08X (nop padding)" % (names[b], a, b))
    lines = ["# Generated by tools/gen_syms.py - do not edit by hand.",
             "# Function names come from symbols/functions.json; extents from tools/funcbounds.py.", ""]
    total = 0
    for name, vstart, vend, rstart in segs:
        tend = A.text_end[name]
        fs = [f for f in funcs if vstart <= f[0] < tend]
        lines += ["[[section]]",
                  'name = "%s_text"' % name,
                  "rom = 0x%08X" % rstart,
                  "vram = 0x%08X" % vstart,
                  "size = 0x%X" % (tend - vstart),
                  "functions = ["]
        for s, e, merged in fs:
            nm = names.get(s, "func_%08X" % s)
            nm = recomp_names.get(nm, nm)
            lines.append('    { name = "%s", vram = 0x%08X, size = 0x%X },' % (nm, s, e - s))
        lines += ["]", ""]
        total += len(fs)
        print("%-5s rom %08X vram %08X..%08X  %d functions" % (name, rstart, vstart, tend, len(fs)))
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print("wrote %s (%d functions)" % (OUT, total))
    # Data symbol file (needed by patches.toml as data_reference_syms_files): data/bss ranges
    # per segment, no named symbols yet.
    dlines = ["# Generated by tools/gen_syms.py - data/bss sections (no symbols yet).", ""]
    bss = {"boot": (0x8001C160, 0x80053710), "main": (0x800DD620, 0x80170000)}
    for name, vstart, vend, rstart in segs:
        tend = A.text_end[name]
        dlines += ["[[section]]", 'name = "%s_data"' % name, "rom = 0x%08X" % (rstart + (tend - vstart)),
                   "vram = 0x%08X" % tend, "size = 0x%X" % (vend - tend), "symbols = []", ""]
        if name in bss:
            b0, b1 = bss[name]
            dlines += ["[[section]]", 'name = "%s_bss"' % name, "vram = 0x%08X" % b0,
                       "size = 0x%X" % (b1 - b0), "symbols = []", ""]
    dout = os.path.join(ROOT, "cspeed.us.datasyms.toml")
    open(dout, "w", encoding="utf-8", newline="\n").write("\n".join(dlines))
    print("wrote %s" % dout)
    # report names that did not land on a function start
    starts = {f[0] for f in funcs}
    for a, n in sorted(names.items()):
        if a not in starts:
            print("WARNING: named address %08X (%s) is not a function start" % (a, n))


if __name__ == "__main__":
    main()
